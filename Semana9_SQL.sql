-- Recuperacion de Datos

-- Informe 1
SELECT 
    'ID:' || cod_asociacion || ' * ' || nombre_asociacion AS ASOCIACION,
    TO_CHAR(fecha_creacion, 'DD-MM-YYYY') AS CREADA,
    tipo AS TIPO
FROM 
    asociacion
WHERE 
    tipo = 'P'
    AND fecha_creacion >= TO_DATE('01/01/2001', 'DD/MM/YYYY')
ORDER BY 
    fecha_creacion DESC;

-- Informe 2
SELECT 
    cod_club AS CLUB,
    nombre_club AS "NOMBRE CLUB",
    patrimonio AS "PATRIMONIO EN PESOS",
    patrimonio / 955 AS "PATRIMONIO EN DOLARES"
FROM 
    club_futbol
WHERE 
    (LOWER(nombre_club) LIKE '%a%' OR LOWER(nombre_club) LIKE '%á%')
    AND patrimonio > 200000000
    AND tipo_club = 'Profesional'
ORDER BY 
    cod_club DESC;
