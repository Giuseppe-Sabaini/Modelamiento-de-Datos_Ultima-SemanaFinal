    CONSTRAINT JUGADOR_ASOCIACION_FK FOREIGN KEY (cod_asociacion) REFERENCES ASOCIACION (cod_asociacion),
    CONSTRAINT JUGADOR_ESCUELA_FK FOREIGN KEY (cod_escuela) REFERENCES ESCUELA_FORMATIVA (cod_escuela)
