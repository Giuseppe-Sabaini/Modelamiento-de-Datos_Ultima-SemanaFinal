CREATE TABLE TIPO_CONTRATO (
    id_tipo_contrato  NUMBER(3) NOT NULL,
    nombre_contrato    NVARCHAR2(30) NOT NULL,
    CONSTRAINT TIPO_CONTRATO_PK PRIMARY KEY (id_tipo_contrato)
);

CREATE TABLE ESCUELA_FORMATIVA (
    cod_escuela     NUMBER(3) NOT NULL,
    nombre_escuela  NVARCHAR2(30) NOT NULL,
    capacidad       NUMBER(5) NOT NULL,
    fecha_fundacion DATE NOT NULL,
    CONSTRAINT ESCUELA_FORMATIVA_PK PRIMARY KEY (cod_escuela)
);

CREATE TABLE ASOCIACION (
    cod_asociacion   NUMBER(3) NOT NULL,
    nombre_asociacion NVARCHAR2(50) NOT NULL,
    fecha_creacion   DATE NOT NULL,
    tipo             NVARCHAR2(20) NOT NULL,
    CONSTRAINT ASOCIACION_PK PRIMARY KEY (cod_asociacion),
    CONSTRAINT ASOCIACION_CHK_FECHA CHECK (fecha_creacion >= TO_DATE('31/12/1980', 'DD/MM/YYYY'))
);

CREATE TABLE COMUNA (
    id_comuna       NUMBER(3) NOT NULL,
    nombre_comuna   NVARCHAR2(30) NOT NULL,
    id_region       NUMBER(3) NOT NULL,
    CONSTRAINT COMUNA_PK PRIMARY KEY (id_comuna),
    CONSTRAINT COMUNA_REGION_FK FOREIGN KEY (id_region) REFERENCES REGION (id_region)
);

CREATE TABLE CLUB_FUTBOL (
    cod_club        NUMBER GENERATED BY DEFAULT AS IDENTITY ( START WITH 703 INCREMENT BY 4),
    nombre_club     NVARCHAR2(30) NOT NULL,
    patrimonio      NUMBER(10) NOT NULL,
    ubicacion       NVARCHAR2(40) NOT NULL,
    tipo_club       NVARCHAR2(30) NOT NULL,
    CONSTRAINT CLUB_FUTBOL_PK PRIMARY KEY (cod_club),
    CONSTRAINT CLUB_FUTBOL_UK_NOMBRE UNIQUE (nombre_club)
